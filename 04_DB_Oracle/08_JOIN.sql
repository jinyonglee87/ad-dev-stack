/*
  OUTER JOIN (포괄 조인 / 외부 조인)
   - 두 테이블 간의 JOIN 시 일치하지 않는 행도 포함시켜서 조회가 가능
   - 단, 반드시 기준이 되는 테이블 컬럼을 지정해야 한다
*/

-- 사원명, 부서명 조회 ORACLE 구문
-- 기준 삼는 테이블의 반대 테이블의 컬럼에 = (+)
-- (+) 한개만 선언 가능
SELECT EMP_NAME, DEPT_TITLE FROM EMPLOYEE, DEPARTMENT
WHERE DEPT_ID(+) = DEPT_CODE;

-- 사원명, 부서명 조회 ANSI 구문
-- 기준 삼는 테이블이 왼쪽이라면 = LEFT JOIN
SELECT EMP_NAME, DEPT_TITLE FROM EMPLOYEE
LEFT JOIN DEPARTMENT ON (DEPT_ID = DEPT_CODE);

-- 사원명, 부서명 조회 ANSI 구문
-- 기준 삼는 테이블이 오른쪽이라면 = RIGHT JOIN
SELECT EMP_NAME, DEPT_TITLE FROM EMPLOYEE
RIGHT JOIN DEPARTMENT ON (DEPT_ID = DEPT_CODE);

-- 사원명, 부서명 조회 ANSI 구문
-- 통합 = FULL JOIN
SELECT EMP_NAME, DEPT_TITLE FROM EMPLOYEE
FULL JOIN DEPARTMENT ON (DEPT_ID = DEPT_CODE);

/*
  NON EQUAL JOIN (비등가 조인)
   - 매칭시킬 컬럼에 대한 조건 작성시 '=' (등호)를 사용하지 않는 조인문
   --> 값의 범위에 포한되는 행들을 연결하는 방식
   - ANSI 구문으로는 JOIN ON으로만 사용가능 (USING 사용 불가)
*/

-- 사원명, 급여, 급여레벨 조회 (ON BETWEEN 사용)
