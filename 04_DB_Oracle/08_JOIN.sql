  테이블 : EMPLOYEE, JOB

  -- JOIN JOB J ON (E.JOB_CODE = J.JOB_CODE); 별칭도 가능
  -- JOIN JOB USING (JOB_CODE); 같은 컬럼 명칭일 경우 USING 가능
