CREATE TABLE LOTTO (
    drawNo NUMBER,
    drawDate DATE,  -- date → drawDate로 변경
    num1 NUMBER,
    num2 NUMBER,
    num3 NUMBER,
    num4 NUMBER,
    num5 NUMBER,
    num6 NUMBER,
    bonus NUMBER
);

SELECT * FROM LOTTO;


/*

NORMAL DISTRIBUTION (FREQUENCY OF NUMBER)

*/
-- NORMAL DISTRIBUTION OF NUMBER SLOT 1
SELECT num1, COUNT(*) AS FREQUENCY
FROM LOTTO
GROUP BY num1
ORDER BY FREQUENCY DESC
FETCH FIRST 5 ROWS ONLY;

