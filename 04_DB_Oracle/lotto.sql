/*

CONSECUTIVE DRAW REPEATING NUMBER

*/

SELECT drawNo, num2, prev_num2
FROM (
  SELECT drawNo, num2,
         LAG(drawNo) OVER (ORDER BY drawNo) AS prev_drawNo,
         LAG(num2) OVER (ORDER BY drawNo) AS prev_num2
  FROM lotto
)
WHERE num2 = prev_num2;
